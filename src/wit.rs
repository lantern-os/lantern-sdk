//! Generate the component's WIT `world` from the manifest — and nothing else, so a
//! component's imports can never exceed its declarations (RFC-0015 §"Generates the
//! component's WIT world", validation rule 6).

use crate::manifest::Manifest;
use crate::registry;

/// The fully-qualified WIT interface identifiers this manifest declares, sorted and
/// de-duplicated. The checkable half of "imports ≤ declarations": a build step compares
/// this against the imports in the component's actual `world`.
pub fn declared_imports(manifest: &Manifest) -> Vec<&'static str> {
    let mut imports: Vec<&'static str> = Vec::new();
    let mut add = |name: &str| {
        if let Some(iface) = registry::lookup(name) {
            if !imports.contains(&iface.wit_import) {
                imports.push(iface.wit_import);
            }
        }
    };
    if !manifest.keystore.is_empty() {
        add("keystore");
    }
    if !manifest.filesystem.is_empty() {
        add("filesystem");
    }
    if manifest.monotonic_clock.is_some() {
        add("monotonic-clock");
    }
    imports.sort_unstable();
    imports
}

/// A complete WIT `world` importing exactly the declared interfaces. The app author adds
/// their own `export`s to a world that includes this one; this is also what a future
/// `lantern-sdk manifest explain` renders.
pub fn generate_world(manifest: &Manifest) -> String {
    let mut out = String::new();
    out.push_str("// Generated by lantern-sdk from lantern.capabilities.toml — do not edit.\n");
    out.push_str(&format!("// app: {} {}\n\n", manifest.app.name, manifest.app.version));
    out.push_str(&format!("package {}:app;\n\n", sanitize_ns(&manifest.app.name)));
    out.push_str("world imports {\n");
    for import in declared_imports(manifest) {
        out.push_str(&format!("    import {import};\n"));
    }
    if declared_imports(manifest).is_empty() {
        out.push_str("    // (the manifest declares no host capabilities)\n");
    }
    out.push_str("}\n");
    out
}

/// A WIT package namespace can't contain `-`-adjacent oddities that a manifest `name`
/// permits at the edges; the manifest charset is already a subset of what WIT allows, so
/// this is a passthrough today, kept as the single place to adjust if that changes.
fn sanitize_ns(name: &str) -> &str {
    name
}
